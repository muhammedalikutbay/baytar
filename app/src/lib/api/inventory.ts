import { call } from './client';
import type { ItemInput, LotInput, ReceiveInput, AdjustInput, ConsumeInput } from './types';
export const list = (includeDeleted = false) => call('inventory_items', { includeDeleted });
export const get = (id: number) => call('inventory_item_get', { id });
export const create = (input: ItemInput) => call('inventory_item_create', { input });
export const update = (id: number, input: ItemInput) => call('inventory_item_update', { id, input });
export const softDelete = (id: number) => call('inventory_item_set_deleted', { id, deleted: true });
export const restore = (id: number) => call('inventory_item_set_deleted', { id, deleted: false });
export const fromCatalog = (kind: 'medication' | 'vaccine', catalogId: number) => call('inventory_from_catalog', { kind, catalogId });
export const lots = (itemId: number, includeDeleted = false) => call('inventory_lots', { itemId, includeDeleted });
export const createLot = (input: LotInput, movedOn: string) => call('inventory_lot_create', { input, movedOn });
export const updateLot = (id: number, input: LotInput, movedOn: string, reason: string) => call('inventory_lot_update', { id, input, movedOn, reason });
export const deleteLot = (id: number) => call('inventory_lot_set_deleted', { id, deleted: true });
export const restoreLot = (id: number) => call('inventory_lot_set_deleted', { id, deleted: false });
export const receive = (input: ReceiveInput) => call('inventory_receive', { input });
export const adjust = (input: AdjustInput) => call('inventory_adjust', { input });
export const writeOffExpired = (itemId: number, today: string) => call('inventory_write_off_expired', { itemId, today });
export const consume = (input: ConsumeInput) => call('inventory_consume', { input });
export const history = (itemId: number) => call('inventory_history', { itemId });
export const lowStock = () => call('inventory_low_stock', {});
export const expiring = (today: string, days = 60) => call('inventory_expiring', { today, days });
export const expired = (today: string) => call('inventory_expired', { today });
export const alerts = (today?: string) => call('inventory_alerts', { today });
